'use strict';
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const srcPath = process.env.JASKINIA_STUDIO_R1_MODEL ||
  path.join(__dirname, '..', '..', '..', 'src', 'jaskinia', '59a-studio-r1-model.js');
const src = fs.readFileSync(srcPath, 'utf8');
const ctx = vm.createContext({});
vm.runInContext(src, ctx);
const M = vm.runInContext('StudioR1Model', ctx);
const d0 = M.make();
assert.equal(M.valid(d0), true);
assert.equal(d0.pixels.length, 576);
assert.equal(M.valid({ ...d0, pixels: d0.pixels.slice(1) }), false);
assert.equal(M.valid({ ...d0, pixels: d0.pixels.map(() => 999) }), false);
const h = M.history(d0);
assert.equal(h.change(d => M.apply(d, [[2,2,3], [3,2,4]])), true);
assert.equal(h.get().revision, 1);
assert.equal(h.get().pixels[2*24+2], 3);
assert.equal(d0.pixels[2*24+2], 0, 'must not mutate caller source');
const snap = h.get(); snap.pixels[2*24+2] = 5;
assert.equal(h.get().pixels[2*24+2], 3, 'must not expose mutable internal state');
assert.equal(h.undo(), true);
assert.equal(h.get().pixels[2*24+2], 0);
assert.equal(h.redo(), true);
assert.equal(h.get().pixels[2*24+2], 3);
assert.equal(h.change(d => M.apply(d, [[2,2,3]])), false, 'no-op must not create history');
assert.equal(h.undo(), true);
assert.equal(h.get().pixels[2*24+2], 0);
assert.equal(h.redo(), true);
assert.equal(h.change(d => M.apply(d, [[2,2,2]])), true);
assert.equal(h.info().canRedo, false, 'new branch discards redo');
assert.throws(() => M.apply(d0, [[-1,4,2]]));
assert.throws(() => M.apply(d0, [[0,0,99]]));
assert.equal(M.valid(h.get()), true);
console.log('PASS: Studio R1 model: validation, immutable stroke, undo/redo, no-op, redo invalidation, bounds');
