'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../../../src/jaskinia/59c-studio-r2-model.js'),'utf8');
const ctx=vm.createContext({});
vm.runInContext(source,ctx);
const M=vm.runInContext('StudioR2Model',ctx);
const first=M.sample();
assert.equal(M.valid(first),true);
assert.equal(first.frames.length,4);
assert.equal(first.frames[0].pixels.length,24*32);
const copied=M.clone(first);
copied.frames[0].pixels[0]=4;
assert.equal(first.frames[0].pixels[0],0,'clone must not mutate source');
assert.equal(M.valid({...first,frames:[{duration:20,pixels:[] }]}),false);
const total=first.frames.reduce((s,f)=>s+f.duration,0);
assert.equal(M.sequenceMs(first),total);
assert.equal(M.frameAt(first,0),0);
assert.equal(M.frameAt(first,first.frames[0].duration),1);
assert.equal(M.frameAt(first,total),0);
assert.equal(M.frameAt(first,-1),3);
const changed=M.edit(first,0,[[0,0,2],[1,0,3]]);
assert.equal(changed.revision,1);
assert.equal(changed.frames[0].pixels[0],2);
assert.equal(first.frames[0].pixels[0],0);
assert.equal(M.edit(first,0,[[0,0,0]]),first,'no-op must preserve document identity');
assert.throws(()=>M.edit(first,0,[[24,0,2]]));
assert.throws(()=>M.edit(first,0,[[0,0,99]]));
const dur=M.duration(first,1,370);
assert.equal(dur.frames[1].duration,370);
assert.equal(M.sequenceMs(dur),total-first.frames[1].duration+370);
const hist=M.history(first);
assert.equal(hist.change(d=>M.edit(d,1,[[0,0,2]])),true);
assert.equal(hist.get().frames[1].pixels[0],2);
assert.equal(hist.undo(),true);
assert.equal(hist.get().frames[1].pixels[0],0);
assert.equal(hist.redo(),true);
assert.equal(hist.get().frames[1].pixels[0],2);
const leak=hist.get();leak.frames[1].pixels[0]=6;
assert.equal(hist.get().frames[1].pixels[0],2);
hist.undo();
hist.change(d=>M.edit(d,1,[[1,0,3]]));
assert.equal(hist.info().canRedo,false,'redo fork must be invalidated');
const world=M.world();
world.tick(80);world.tick(80);world.tick(80);
const before=world.snap();
assert(before.particles.length>0 && before.timeMs===240);
const sourceEdited=M.edit(first,0,[[2,2,4]]);
assert.equal(sourceEdited.revision,1);
assert.deepEqual(world.snap(),before,'changing document must not mutate world time, particles or history');
world.tick(90);
const after=world.snap();
assert.equal(after.timeMs,330);
assert(after.created>=before.created && after.particles.some(p=>before.particles.some(b=>b.id===p.id)));
world.pause(true);world.tick(90);
assert.equal(world.snap().timeMs,330);
world.pause(false);
world.move(.14,.7);
assert.equal(world.snap().auto,false);
assert.equal(world.snap().ship.x,.14);
world.tick(76);
assert.equal(world.snap().timeMs,406);
const t=world.snap();t.particles[0].x=-900;
assert.notEqual(world.snap().particles[0].x,-900,'snapshot must not leak mutable particle state');
console.log('PASS Studio R2: validated frames, independent source clock, immutable edits/history, source changes never reset world, world pause/ship/particles');
