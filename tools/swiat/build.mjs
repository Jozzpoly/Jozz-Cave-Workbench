// node tools/swiat/build.mjs → src/vendor/swiat3d.js
// The bundle defines window.__SWIAT3D_FACTORY: parsing it costs little, three.js only starts when a 3D window first asks.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.join(here, '..', '..', 'src', 'vendor', 'swiat3d.js');
const pkg = n => JSON.parse(fs.readFileSync(path.join(here, 'node_modules', n, 'package.json'), 'utf8')).version;
const r = await build({ entryPoints: [path.join(here, 'entry.js')], bundle: true, format: 'iife', globalName: '__SWIAT3D_MOD', minify: true, write: false, legalComments: 'none', target: ['es2020'], logLevel: 'warning' });
const code = r.outputFiles[0].text;
const head = `/*! Jaskinia's 3D runtime, generated by tools/swiat/build.mjs. three.js ${pkg('three')} (MIT, https://github.com/mrdoob/three.js/blob/dev/LICENSE), three-mesh-bvh ${pkg('three-mesh-bvh')} (MIT, https://github.com/gkjohnson/three-mesh-bvh/blob/master/LICENSE). Do not edit by hand. */\n`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, head + 'window.__SWIAT3D_FACTORY = function () {\n' + code + '\nreturn __SWIAT3D_MOD;\n};\n');
console.log('swiat3d.js', (fs.statSync(out).size / 1024).toFixed(0), 'KB', 'three', pkg('three'), 'bvh', pkg('three-mesh-bvh'));
